def build_weekly_stats(
    day: int,
    week_completed: set,
    all_completed: set,
    group_stats: dict = None,
) -> str:
    week = day // 7
    if week < 1 or week > 11:
        return ""

    header = get_weekly_header(week)
    total_done = len(all_completed)
    week_done = len(week_completed)

    pct_label, pct_context = get_planet_percentile(total_done)

    lines = [header, ""]
    lines.append(f"📅 *Эта неделя:* {week_done} из 7 дней засчитано")
    lines.append(f"📈 *Всего засчитано:* {total_done} дней из {day}")
    lines.append("")

    if group_stats:
        total_g  = group_stats.get("total", 0)
        active_g = group_stats.get("active", 0)
        dropped_g = group_stats.get("dropped", 0)
        if total_g > 0:
            pct_active = round(active_g / total_g * 100)
            lines.append(f"👥 *Группа:* {total_g} участников")
            lines.append(f"✅ Продолжают: {active_g} ({pct_active}%)")
            lines.append(f"❌ Сошли: {dropped_g}")
            lines.append("")

    lines.append(f"🌍 *Ты в {pct_label} людей на планете*,")
    lines.append(f"_{pct_context}._")

    next_m = get_next_percentile_milestone(total_done)
    if next_m:
        days_until, next_label = next_m
        if days_until == 1:
            lines.append(f"_Ещё 1 день — и войдёшь в {next_label}._")
        elif days_until <= 7:
            lines.append(f"_До {next_label} — всего {days_until} дней._")

    return "\n".join(lines)


