def get_mind_task(day: int) -> dict:
    """Задача направления 🧠 Мышление для Модуля 2"""
    if 22 <= day <= 28:
        label = "Намерение"
        description = "Запиши: 1 главная задача на сегодня + 1 конкретный шаг к ней"
    elif 29 <= day <= 35:
        label = "Намерение"
        description = "Утром: цель дня + шаг к ней. Плюс: что может помешать — и как обойти?"
    else:  # 36–42
        label = "Фокус"
        description = "Намерение утром + 25 мин без телефона и уведомлений на главную задачу дня"
    return {"icon": "🧠", "label": label, "description": description}


