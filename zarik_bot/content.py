def get_morning(day: int) -> str:
    idx = max(0, min(day - 1, len(MORNING) - 1))
    return MORNING[idx]


def get_afternoon(day: int, all_done: bool) -> str:
    """Fallback функция (используется как запасная)."""
    if all_done:
        return AFTERNOON_DONE[(day - 1) % len(AFTERNOON_DONE)]
    return AFTERNOON_NOT_DONE[(day - 1) % len(AFTERNOON_NOT_DONE)]


def get_afternoon_smart(day: int, completed: set) -> str:
    """Умное дневное сообщение 14:00 с учётом конкретных незакрытых задач."""
    done = len(completed)
    if done >= 5:
        return AFTERNOON_DONE[(day - 1) % len(AFTERNOON_DONE)]
    remaining = [TASK_NAMES[i] for i in range(5) if i not in completed]
    tasks_str = "\n".join(remaining)
    if done == 0:
        if day <= len(AFTERNOON_ZERO_DAILY):
            return AFTERNOON_ZERO_DAILY[day - 1]
        return AFTERNOON_ZERO
    else:
        if day <= len(AFTERNOON_PARTIAL_DAILY):
            return AFTERNOON_PARTIAL_DAILY[day - 1].format(tasks=tasks_str)
        return AFTERNOON_PARTIAL.format(tasks=tasks_str)


