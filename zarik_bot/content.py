def get_planet_percentile(days_done: int) -> tuple:
    if days_done <= 0:
        return ("топ 30%", _PERCENTILE_CURVE[0][2])
    curve = _PERCENTILE_CURVE
    if days_done >= curve[-1][0]:
        return (_format_pct(curve[-1][1]), curve[-1][2])
    for i in range(len(curve) - 1):
        d0, p0, ctx = curve[i]
        d1, p1, _   = curve[i + 1]
        if d0 <= days_done < d1:
            t   = (days_done - d0) / (d1 - d0)
            pct = p0 + t * (p1 - p0)
            return (_format_pct(pct), ctx)
    last = curve[-1]
    return (_format_pct(last[1]), last[2])


def get_next_percentile_milestone(days_done: int) -> tuple | None:
    for d, p, _ in _PERCENTILE_CURVE:
        if d > days_done:
            return (d - days_done, _format_pct(p))
    return None


def _format_pct(pct: float) -> str:
    if pct >= 10:
        return f"топ {round(pct)}%"
    elif pct >= 1:
        return f"топ {round(pct, 1)}%"
    elif pct >= 0.1:
        return f"топ {round(pct, 2)}%"
    else:
        return f"топ {round(pct, 3)}%"


