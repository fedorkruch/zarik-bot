def get_exercise_block(day: int) -> str:
    """Формирует текст задачи зарядки с учётом прогрессии"""
    reps = 9 + day  # 10 в день 1, 30 в день 21

    if day <= 7:
        return (
            f"{reps} отжиманий, {reps} на пресс, {reps} наклонов, {reps} приседаний\n"
            f"_(1 круг)_"
        )
    elif day <= 14:
        return (
            f"{reps} отжиманий, {reps} на пресс, {reps} наклонов, {reps} приседаний\n"
            f"_(2 круга, отдых 5 мин между ними)_"
        )
    else:
        return (
            f"{reps} отжиманий, {reps} на пресс, {reps} наклонов, {reps} приседаний\n"
            f"_(2 круга обязательно, 3-й — по ощущениям)_"
        )


def get_evening_task(day: int) -> str:
    """Формирует текст вечернего задания с учётом прогрессии"""
    if day <= 7:
        minutes = 20
    elif day <= 14:
        minutes = 30
    else:
        minutes = 40

    return f"Выбери одно: лечь на {minutes} мин раньше / убери телефон за {minutes} мин до сна / {minutes} мин чтения"


